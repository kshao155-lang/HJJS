# 重新实现 emit（sft_build.emit 绑定其自身全局 out，不可直接复用）
OUT = []


def emit2(family, refs, user, assistant):
    ok, bad, nl = qc(assistant)
    OUT.append({
        "id": f"b2_{len(OUT)+1:04d}",
        "family": family,
        "spec_refs": refs,
        "audit": "pending",
        "qc": {"quote_ok": ok, "bad_quotes": bad, "labels": nl},
        "messages": [
            {"role": "system", "content": SYSTEM},
            {"role": "user", "content": user},
            {"role": "assistant", "content": assistant},
        ],
    })


