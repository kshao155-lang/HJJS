"""数据：中国历史王朝与治乱数据集（供"皇极模型"训练）。

标注口径（人工整定，取通行史学结论的粗粒度近似，天文年记法：公元前 n 年 = -n+1）：
  * 王朝表 DYNASTIES：(名, 起, 止) —— 用于"我观"特征与分期抽样；
  * 盛世 SHENG SPAN —— 史称"之治/之世/盛世"的时段 → 标签 2（盛）；
  * 乱世 LUAN  SPAN —— 大分裂、大战乱时段 → 标签 0（乱），优先级高于盛世；
  * 其余王朝内年份 → 标签 1（平）；无王朝覆盖的空档 → 标签 0（乱，过渡动荡）。
  * 春秋（东周）视为"平"（王室虽衰、秩序犹存），战国入乱世。

这是邵雍"皇帝王伯/四时"标签思想的操作化：给每一年贴上"季节"。
 granularity 为年，训练时逐年第样本。
"""

